"""Offline tests of packaging/release_version.py."""

import importlib.util
import pathlib
import unittest

spec = importlib.util.spec_from_file_location(
    "release_version", pathlib.Path(__file__).with_name("release_version.py"))
rv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rv)

TOML = """[workspace]
members = ["crates/a"]

[workspace.package]
version = "0.4.0"
edition = "2021"

[workspace.dependencies]
serde = { version = "1.0" }
"""

LOCK = """# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "a"
version = "0.4.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "0.4.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""


class NextVersion(unittest.TestCase):
    def test_base_unused_is_taken_as_is(self):
        self.assertEqual(rv.next_version("0.5.0", ["v0.4.0", "v0.4.1"]), "0.5.0")

    def test_first_free_patch_after_used_ones(self):
        self.assertEqual(rv.next_version("0.4.0", ["v0.4.0", "v0.4.1"]), "0.4.2")

    def test_base_above_used_patches_wins(self):
        self.assertEqual(rv.next_version("0.4.2", ["v0.4.0", "v0.4.1"]), "0.4.2")

    def test_numbers_never_go_back_after_a_gap(self):
        self.assertEqual(rv.next_version("0.4.0", ["v0.4.0", "v0.4.5"]), "0.4.6")

    def test_other_minors_and_junk_are_ignored(self):
        names = ["v0.3.9", "v1.4.7", "untagged-6bb7933e", "", "v0.4.x"]
        self.assertEqual(rv.next_version("0.4.0", names), "0.4.0")

    def test_bad_base_is_refused(self):
        with self.assertRaises(SystemExit):
            rv.next_version("0.4", [])


class SetVersion(unittest.TestCase):
    def test_base_version_reads_workspace_package(self):
        self.assertEqual(rv.base_version(TOML), "0.4.0")

    def test_toml_changes_only_the_workspace_version(self):
        out = rv.set_cargo_toml(TOML, "0.4.2")
        self.assertIn('[workspace.package]\nversion = "0.4.2"', out)
        self.assertIn('serde = { version = "1.0" }', out)
        self.assertEqual(out.count("0.4.2"), 1)

    def test_lock_changes_workspace_crates_not_registry_ones(self):
        out = rv.set_cargo_lock(LOCK, "0.4.0", "0.4.2")
        self.assertIn('name = "a"\nversion = "0.4.2"', out)
        self.assertIn('name = "serde"\nversion = "0.4.0"', out)
        self.assertTrue(out.startswith("# This file"))

    def test_lock_without_the_old_version_is_refused(self):
        with self.assertRaises(SystemExit):
            rv.set_cargo_lock(LOCK, "0.9.9", "1.0.0")


class Files(unittest.TestCase):
    def test_crlf_files_keep_their_endings(self):
        import tempfile
        with tempfile.TemporaryDirectory() as d:
            path = pathlib.Path(d) / "Cargo.lock"
            path.write_bytes(LOCK.replace("\n", "\r\n").encode())
            text, crlf = rv.read(path)
            self.assertTrue(crlf)
            rv.write(path, rv.set_cargo_lock(text, "0.4.0", "0.4.2"), crlf)
            data = path.read_bytes().decode()
            self.assertIn('name = "a"\r\nversion = "0.4.2"\r\n', data)
            self.assertNotIn("\r\r", data)
            self.assertEqual(data.count("\n"), data.count("\r\n"))


if __name__ == "__main__":
    unittest.main()
